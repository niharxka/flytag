/**
 * tokens.json → the three files the app reads (spec §5.1). Run with `npm run tokens`.
 *
 *   src/theme/tokens.ts         typed values for code that can't use classNames (Reanimated, SVG, shadows)
 *   global.css                  CSS variables for NativeWind: Mist in :root, Charcoal under the dark media query
 *   src/theme/tailwind.tokens.js  the names tailwind.config.js maps to classes (bg-mist, p-space-4, rounded-pill…)
 *
 * Colours live in CSS variables (not baked into classes) so switching theme is a variable swap:
 * every `bg-surface` re-resolves without components knowing a theme exists.
 * Plain Node (24+ strips the types), no dependencies, so it runs in CI before anything is installed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Themed = { light: string; dark: string };
type ColorToken = { name: string; value: string | Themed };
type TypeStyle = {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
};
type Named = { name: string; value: string };
type Tokens = {
  color: { tokens: ColorToken[] };
  type: { groups: { styles: TypeStyle[] }[] };
  spacing: { tokens: Named[] };
  radius: { tokens: Named[] };
  shadow: { tokens: { name: string; value: string | Themed }[] };
  blur: { tokens: Named[] };
  size: { tokens: Named[] };
};

const root = join(import.meta.dirname, '..');
const tokens: Tokens = JSON.parse(readFileSync(join(root, 'docs/design/tokens.json'), 'utf8'));
const HEADER =
  '// GENERATED by scripts/build-tokens.ts from docs/design/tokens.json. Do not edit; run `npm run tokens`.\n';

const px = (v: string) => Number.parseFloat(v);

// Plane-only colours (flare…) have a single value; give them the same value in both themes.
function themed(value: string | Themed): Themed {
  return typeof value === 'string' ? { light: value, dark: value } : value;
}

// `focus` is written as "{sky-deep}" — an alias to another token, resolved per theme.
const rawColors = new Map(tokens.color.tokens.map((t) => [t.name, themed(t.value)]));
function resolve(value: string, theme: keyof Themed): string {
  const alias = /^\{(.+)\}$/.exec(value);
  if (!alias) return value;
  const target = rawColors.get(alias[1]);
  if (!target) throw new Error(`Unknown colour alias ${value}`);
  return resolve(target[theme], theme);
}
const colors = [...rawColors].map(([name, v]) => ({
  name,
  light: resolve(v.light, 'light'),
  dark: resolve(v.dark, 'dark'),
}));

// React Native can't pick a weight from one family on Android, so each weight is its own
// family name, matching the keys loaded with useFonts in src/theme/fonts.ts.
const FONT_FILES: Record<number, string> = {
  400: 'OpenSauceOne-Regular',
  500: 'OpenSauceOne-Medium',
  600: 'OpenSauceOne-SemiBold',
  700: 'OpenSauceOne-Bold',
  800: 'OpenSauceOne-ExtraBold',
  900: 'OpenSauceOne-Black',
};
// `fine` (300) is slides-only per the brand rules, so it never reaches the app.
const typeStyles = tokens.type.groups
  .flatMap((g) => g.styles)
  .filter((s) => s.name !== 'fine')
  .map((s) => {
    const size = px(s.fontSize);
    const family = FONT_FILES[s.fontWeight];
    if (!family) throw new Error(`No font file for weight ${s.fontWeight} (${s.name})`);
    return {
      name: s.name,
      fontFamily: family,
      fontSize: size,
      lineHeight: px(s.lineHeight),
      // em → px, because React Native letterSpacing is absolute.
      letterSpacing: s.letterSpacing ? Math.round(px(s.letterSpacing) * size * 100) / 100 : 0,
      uppercase: s.name === 'label',
    };
  });

const scale = (list: Named[], strip = '') =>
  Object.fromEntries(list.map((t) => [t.name.replace(strip, ''), px(t.value)]));
const spacing = scale(tokens.spacing.tokens);
const radius = scale(tokens.radius.tokens, 'radius-');
const size = scale(tokens.size.tokens);
const blur = scale(tokens.blur.tokens);
const shadows = Object.fromEntries(
  tokens.shadow.tokens.map((t) => [t.name.replace('shadow-', ''), themed(t.value)]),
);

const camel = (s: string) => s.replace(/-(.)/g, (_, c: string) => c.toUpperCase());
const json = (v: unknown) => JSON.stringify(v, null, 2);

// ---- src/theme/tokens.ts
const colorObj = (theme: keyof Themed) => Object.fromEntries(colors.map((c) => [camel(c.name), c[theme]]));
const tokensTs = `${HEADER}
export const colors = {
  light: ${json(colorObj('light')).replace(/\n/g, '\n  ')},
  dark: ${json(colorObj('dark')).replace(/\n/g, '\n  ')},
} as const;

export type ThemeName = keyof typeof colors;
export type ColorName = keyof (typeof colors)['light'];

/** React Native boxShadow strings (RN ≥ 0.76), per theme. */
export const shadows = ${json(shadows)} as const;

export const spacing = ${json(Object.fromEntries(Object.entries(spacing).map(([k, v]) => [camel(k), v])))} as const;

export const radius = ${json(radius)} as const;

export const size = ${json(Object.fromEntries(Object.entries(size).map(([k, v]) => [camel(k), v])))} as const;

export const blur = ${json(Object.fromEntries(Object.entries(blur).map(([k, v]) => [camel(k), v])))} as const;

export const type = ${json(
  Object.fromEntries(
    typeStyles.map(({ name, uppercase, ...style }) => [
      camel(name),
      uppercase ? { ...style, textTransform: 'uppercase' } : style,
    ]),
  ),
)} as const;

export type TypeName = keyof typeof type;
`;

// ---- global.css
const vars = (theme: keyof Themed, indent: string) =>
  colors.map((c) => `${indent}--${c.name}: ${c[theme]};`).join('\n');
const typeClasses = typeStyles
  .map(
    (s) =>
      `  .type-${s.name} {\n    font-family: ${s.fontFamily};\n    font-size: ${s.fontSize}px;\n    line-height: ${s.lineHeight}px;\n    letter-spacing: ${s.letterSpacing}px;${s.uppercase ? '\n    text-transform: uppercase;' : ''}\n  }`,
  )
  .join('\n');
const globalCss = `/* GENERATED by scripts/build-tokens.ts from docs/design/tokens.json. Do not edit; run \`npm run tokens\`. */
@tailwind base;
@tailwind components;
@tailwind utilities;

/* Mist (light) */
:root {
${vars('light', '  ')}
}

/* Charcoal (dark). NativeWind's colorScheme.set() drives this media query on native. */
@media (prefers-color-scheme: dark) {
  :root {
${vars('dark', '    ')}
  }
}

/* Type styles: one class per token, e.g. className="type-heading text-ink". */
@layer components {
${typeClasses}
}
`;

// ---- src/theme/tailwind.tokens.js (CommonJS: tailwind.config.js loads it with require)
const tailwindTokens = `${HEADER}
module.exports = {
  colors: ${json(Object.fromEntries(colors.map((c) => [c.name, `var(--${c.name})`]))).replace(/\n/g, '\n  ')},
  spacing: ${json(Object.fromEntries(Object.entries({ ...spacing, ...size }).map(([k, v]) => [k, `${v}px`]))).replace(/\n/g, '\n  ')},
  borderRadius: ${json(Object.fromEntries(Object.entries(radius).map(([k, v]) => [k, `${v}px`]))).replace(/\n/g, '\n  ')},
  // font-400 … font-900 pick the font file for a weight (fontWeight alone can't on Android).
  fontFamily: ${json(FONT_FILES).replace(/\n/g, '\n  ')},
};
`;

writeFileSync(join(root, 'src/theme/tokens.ts'), tokensTs);
writeFileSync(join(root, 'global.css'), globalCss);
writeFileSync(join(root, 'src/theme/tailwind.tokens.js'), tailwindTokens);
console.log(
  `tokens: ${colors.length} colours, ${typeStyles.length} type styles → tokens.ts, global.css, tailwind.tokens.js`,
);
