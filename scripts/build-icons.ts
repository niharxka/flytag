/**
 * assets/icons/*.svg → src/ui/icons.generated.ts. Run with `npm run icons`.
 *
 * The FlyTag set only uses <path> and <circle> on a 24 grid with shared stroke settings, so we
 * keep just the shapes and let <Icon> apply the stroke. That's simpler than SVGR (no dependency,
 * one file) and gives a typed IconName: a misspelled icon fails typecheck.
 * Add an icon: drop `name.svg` in assets/icons/ (24 grid, stroke only) and rerun.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

type Shape = { type: 'path'; d: string } | { type: 'circle'; cx: number; cy: number; r: number };

const root = join(import.meta.dirname, '..');
const dir = join(root, 'assets/icons');

const attr = (tag: string, name: string) => {
  const m = new RegExp(`\\b${name}="([^"]*)"`).exec(tag);
  if (!m) throw new Error(`Missing ${name} in ${tag}`);
  return m[1];
};

const icons: Record<string, Shape[]> = {};
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()) {
  const svg = readFileSync(join(dir, file), 'utf8');
  const shapes: Shape[] = [];
  for (const [tag, kind] of svg.matchAll(/<(path|circle)\b[^>]*>/g).map((m) => [m[0], m[1]] as const)) {
    shapes.push(
      kind === 'path'
        ? { type: 'path', d: attr(tag, 'd') }
        : { type: 'circle', cx: +attr(tag, 'cx'), cy: +attr(tag, 'cy'), r: +attr(tag, 'r') },
    );
  }
  if (shapes.length === 0) throw new Error(`${file} has no <path> or <circle>`);
  icons[basename(file, '.svg')] = shapes;
}

writeFileSync(
  join(root, 'src/ui/icons.generated.ts'),
  `// GENERATED by scripts/build-icons.ts from assets/icons/*.svg. Do not edit; run \`npm run icons\`.

export const icons = ${JSON.stringify(icons, null, 2)} as const;

export type IconName = keyof typeof icons;
`,
);
console.log(`icons: ${Object.keys(icons).length} → src/ui/icons.generated.ts`);
